function s = ternary_str(cond, a, b)
if cond, s = a; else, s = b; end
end

function colors = tab20_colors(n)
% Palette qualitative à fort contraste (équivalent tab20 / Paired),
% conçue pour rester distinguable jusqu'à 20 classes
    base = [ ...
        0.122 0.467 0.706;  0.682 0.780 0.910;  ...
        1.000 0.498 0.055;  1.000 0.733 0.471;  ...
        0.173 0.627 0.173;  0.596 0.875 0.541;  ...
        0.839 0.153 0.157;  1.000 0.598 0.588;  ...
        0.580 0.404 0.741;  0.773 0.690 0.835;  ...
        0.549 0.337 0.294;  0.769 0.611 0.580;  ...
        0.890 0.467 0.761;  0.969 0.714 0.824;  ...
        0.498 0.498 0.498;  0.780 0.780 0.780;  ...
        0.737 0.741 0.133;  0.859 0.859 0.553;  ...
        0.090 0.745 0.812;  0.620 0.855 0.898];
    if n <= size(base,1)
        colors = base(1:n,:);
    else
        colors = hsv2rgb([linspace(0,1,n)' 0.8*ones(n,1) 0.9*ones(n,1)]);
    end
end